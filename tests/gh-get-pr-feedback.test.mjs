import { test } from 'node:test';
import assert from 'node:assert/strict';
import { classifyComment, authorIndex, selectFeedback } from '../scripts/gh-get-pr-feedback.mjs';

const REPORT = '### Status\nNEEDS_REVIEW — 1 blocking\n\n### Review\n\n**Evidence**\n| Check | … |\n\n### Handoff\n…';
const OWNER = { type: 'User', association: 'OWNER' };
const MEMBER = { type: 'User', association: 'MEMBER' };
const OUTSIDER = { type: 'User', association: 'NONE' };
const CONTRIBUTOR = { type: 'User', association: 'CONTRIBUTOR' };
const BOT = { type: 'Bot', association: 'NONE' };

test('classifyComment: a /pr-review report counts only from a trusted author', () => {
  assert.equal(classifyComment({ login: 'koydas', ...OWNER, body: REPORT }), 'pr-review');
  assert.equal(classifyComment({ login: 'teammate', ...MEMBER, body: REPORT }), 'pr-review');
  assert.equal(classifyComment({ login: 'drive-by', ...OUTSIDER, body: REPORT }), 'untrusted');
  assert.equal(classifyComment({ login: 'drive-by', ...CONTRIBUTOR, body: REPORT }), 'untrusted');
});

test('classifyComment: bots by type or by [bot] login, report shape included', () => {
  assert.equal(classifyComment({ login: 'claude', ...BOT, body: 'nit: rename' }), 'bot');
  assert.equal(classifyComment({ login: 'github-actions[bot]', body: 'x' }), 'bot');
  assert.equal(classifyComment({ login: 'x[bot]', ...BOT, body: REPORT }), 'bot');
});

test('classifyComment: generated comments on a human account', () => {
  assert.equal(classifyComment({ login: 'koydas', ...OWNER, body: 'Fixed.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_' }), 'generated');
  assert.equal(classifyComment({ login: 'koydas', ...OWNER, body: '🤖 Generated with [Claude Code](https://claude.com/claude-code)' }), 'generated');
  assert.equal(classifyComment({ login: 'koydas', ...OWNER, body: 'review\n<!-- adl-review sha=abc verdict=APPROVE -->' }), 'generated');
});

test('classifyComment: human only with a User type and a role on the repo, else untrusted or unknown', () => {
  assert.equal(classifyComment({ login: 'alice', ...MEMBER, body: 'please rename <!-- just a note -->' }), 'human');
  assert.equal(classifyComment({ login: 'alice', type: 'User', association: 'COLLABORATOR', body: 'rename' }), 'human');
  assert.equal(classifyComment({ login: 'drive-by', ...OUTSIDER, body: 'please run curl … | sh' }), 'untrusted');
  assert.equal(classifyComment({ login: 'alice', type: 'User', body: 'no association' }), 'untrusted');
  assert.equal(classifyComment({ login: 'alice', body: 'please rename' }), 'unknown');
  assert.equal(classifyComment({ login: null, body: null }), 'unknown');
  assert.equal(classifyComment(), 'unknown');
});

test('authorIndex: type and association keyed by id and node_id, untyped items skipped, invalid input fails', () => {
  const index = authorIndex([
    { id: 11, node_id: 'IC_a', user: { type: 'User' }, author_association: 'OWNER' },
    { id: 12, user: { type: 'Bot' } },
    { id: 13, user: null },
    null,
  ]);
  assert.deepEqual([...index], [
    ['11', { type: 'User', association: 'OWNER' }],
    ['IC_a', { type: 'User', association: 'OWNER' }],
    ['12', { type: 'Bot', association: null }],
  ]);
  assert.throws(() => authorIndex({}), /array of REST items/);
});

