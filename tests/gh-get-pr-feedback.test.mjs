test('selectFeedback: latest trusted /pr-review report, human comments and reviews; bots counted', () => {
  const out = selectFeedback(activity, index);
  assert.equal(out.source, 'rest+ccr');
  assert.equal(out.latestPrReview.id, 'IC_r2', 'a newer report-shaped comment from an outsider never becomes the report');
  assert.deepEqual(out.human.comments.map((c) => c.id), ['IC_h']);
  assert.deepEqual(out.human.reviews.map((r) => [r.id, r.state]), [['PRR_h', 'CHANGES_REQUESTED']]);
  assert.deepEqual(out.excluded, { bot: 4 });
});

test('selectFeedback: generated, untrusted and unknown items are listed, never applied', () => {
  const { notApplied } = selectFeedback(activity, index);
  assert.deepEqual(notApplied.untrusted.map((u) => u.id), ['IC_fake', 'IC_out', 6, 9]);
  assert.deepEqual(notApplied.generated.map((u) => u.id), ['IC_gen', 10]);
  assert.deepEqual(notApplied.unknown.map((u) => u.id), ['IC_missing']);
  assert.deepEqual([notApplied.untrusted[2].path, notApplied.untrusted[2].line], ['e.mjs', 7]);
});

test('selectFeedback: threads keep requests and a bot root only — bot-only, resolved and outsider-only threads dropped', () => {
  const { threads } = selectFeedback(activity, index).human;
  assert.deepEqual(threads.map((t) => t.threadId), ['T1', 'T2', 'T5']);
  assert.deepEqual(threads[1].comments.map((c) => [c.id, c.class]), [[2, 'bot'], [3, 'human']]);
  assert.equal(threads[1].resolved, null);
  assert.deepEqual(threads[2].comments.map((c) => [c.id, c.class]), [[7, 'human']], 'outsider root, bot reply, outsider and generated replies are not passed');
  assert.ok(threads.every((t) => t.comments.every((c) => !('root' in c))));
});

test('selectFeedback: a trusted /pr-review report posted as a review body counts as the report', () => {
  const out = selectFeedback({ threads: [], reviews: [{ id: 'PRR_h', author: { login: 'alice' }, body: REPORT, state: 'COMMENTED', submittedAt: '2026-10-09T00:00:00Z' }] }, index);
  assert.equal(out.latestPrReview.id, 'PRR_h');
  assert.equal(out.source, null);
});

test('selectFeedback: no report → null; invalid input fails loudly', () => {
  assert.equal(selectFeedback({ threads: [] }, new Map()).latestPrReview, null);
  assert.throws(() => selectFeedback({}, new Map()), /threads/);
  assert.throws(() => selectFeedback({ threads: [] }, {}), /author index/);
});
