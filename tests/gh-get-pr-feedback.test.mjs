import { test } from 'node:test';
import assert from 'node:assert/strict';
import { classifyComment, authorTypeIndex, selectFeedback } from '../scripts/gh-get-pr-feedback.mjs';

const REPORT = '### Status\nNEEDS_REVIEW — 1 blocking\n\n### Review\n\n**Evidence**\n| Check | … |\n\n### Handoff\n…';

test('classifyComment: a /pr-review report wins over its author', () => {
  assert.equal(classifyComment({ login: 'koydas', type: 'User', body: REPORT }), 'pr-review');
  assert.equal(classifyComment({ login: 'x[bot]', type: 'Bot', body: REPORT }), 'pr-review');
});

test('classifyComment: bots by type or by [bot] login', () => {
  assert.equal(classifyComment({ login: 'claude', type: 'Bot', body: 'nit: rename' }), 'bot');
  assert.equal(classifyComment({ login: 'github-actions[bot]', type: null, body: 'x' }), 'bot');
});

test('classifyComment: generated comments on a human account', () => {
  assert.equal(classifyComment({ login: 'koydas', type: 'User', body: 'Fixed.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_' }), 'generated');
  assert.equal(classifyComment({ login: 'koydas', type: 'User', body: '🤖 Generated with [Claude Code](https://claude.com/claude-code)' }), 'generated');
  assert.equal(classifyComment({ login: 'koydas', type: 'User', body: 'review\n<!-- adl-review sha=abc verdict=APPROVE -->' }), 'generated');
});

test('classifyComment: human only with a known User type, else unknown', () => {
  assert.equal(classifyComment({ login: 'alice', type: 'User', body: 'please rename <!-- just a note -->' }), 'human');
  assert.equal(classifyComment({ login: 'alice', type: null, body: 'please rename' }), 'unknown');
  assert.equal(classifyComment({ login: null, type: null, body: null }), 'unknown');
  assert.equal(classifyComment(), 'unknown');
});

test('authorTypeIndex: keyed by id and node_id, untyped items skipped, invalid input fails', () => {
  const index = authorTypeIndex([
    { id: 11, node_id: 'IC_a', user: { type: 'User' } },
    { id: 12, user: { type: 'Bot' } },
    { id: 13, user: null },
    null,
  ]);
  assert.deepEqual([...index], [['11', 'User'], ['IC_a', 'User'], ['12', 'Bot']]);
  assert.throws(() => authorTypeIndex({}), /array of REST items/);
});

const types = new Map([
  ['IC_h', 'User'], ['IC_r1', 'User'], ['IC_r2', 'User'], ['IC_bot', 'Bot'], ['IC_gen', 'User'],
  ['PRR_h', 'User'], ['PRR_empty', 'User'], ['PRR_bot', 'Bot'],
  ['1', 'User'], ['2', 'Bot'], ['3', 'User'], ['4', 'Bot'], ['5', 'User'],
]);
const activity = {
  source: 'rest+ccr',
  prComments: [
    { id: 'IC_r1', author: { login: 'koydas' }, body: REPORT, createdAt: '2026-10-01T00:00:00Z', url: 'u1' },
    { id: 'IC_h', author: { login: 'alice' }, body: 'nit: typo in README', createdAt: '2026-10-02T00:00:00Z', url: 'u2' },
    { id: 'IC_r2', author: { login: 'koydas' }, body: REPORT + '\nv2', createdAt: '2026-10-03T00:00:00Z', url: 'u3' },
    { id: 'IC_bot', author: { login: 'github-actions' }, body: 'Auto-fix rejected', createdAt: '2026-10-02T00:00:00Z' },
    { id: 'IC_gen', author: { login: 'koydas' }, body: 'x <!-- adl-review sha=a verdict=APPROVE -->', createdAt: '2026-10-02T00:00:00Z' },
    { id: 'IC_missing', author: { login: 'ghost' }, body: 'who?', createdAt: '2026-10-02T00:00:00Z' },
  ],
  reviews: [
    { id: 'PRR_h', author: { login: 'alice' }, body: 'Rename the helper.', state: 'CHANGES_REQUESTED', submittedAt: '2026-10-02T00:00:00Z' },
    { id: 'PRR_empty', author: { login: 'alice' }, body: '', state: 'APPROVED', submittedAt: '2026-10-02T00:00:00Z' },
    { id: 'PRR_bot', author: { login: 'claude' }, body: 'Review summary', state: 'COMMENTED', submittedAt: '2026-10-02T00:00:00Z' },
  ],
  threads: [
    { id: 1, threadId: 'T1', path: 'a.mjs', line: 3, author: 'alice', body: 'nit: name', createdAt: 't', resolved: false, outdated: false, replies: [] },
    { id: 2, threadId: 'T2', path: 'b.mjs', line: 4, author: 'codex', body: 'P2: edge case', createdAt: 't', resolved: null, outdated: false,
      replies: [{ id: 3, author: 'alice', body: 'agreed, fix it', createdAt: 't' }] },
    { id: 4, threadId: 'T3', path: 'c.mjs', line: 5, author: 'codex', body: 'P3: style', createdAt: 't', resolved: false, outdated: false, replies: [] },
    { id: 5, threadId: 'T4', path: 'd.mjs', line: 6, author: 'alice', body: 'done?', createdAt: 't', resolved: true, outdated: false, replies: [] },
  ],
};

test('selectFeedback: latest /pr-review report, human comments and reviews, bots and generated left out', () => {
  const out = selectFeedback(activity, types);
  assert.equal(out.source, 'rest+ccr');
  assert.equal(out.latestPrReview.id, 'IC_r2');
  assert.deepEqual(out.human.comments.map((c) => c.id), ['IC_h']);
  assert.deepEqual(out.human.reviews.map((r) => [r.id, r.state]), [['PRR_h', 'CHANGES_REQUESTED']]);
  assert.deepEqual(out.unknown.map((u) => u.id), ['IC_missing']);
  assert.deepEqual(out.excluded, { bot: 3, generated: 1 });
});

test('selectFeedback: threads — human root kept, bot thread kept whole when a human replied, bot-only and resolved dropped', () => {
  const { threads } = selectFeedback(activity, types).human;
  assert.deepEqual(threads.map((t) => t.threadId), ['T1', 'T2']);
  assert.deepEqual(threads[1].comments.map((c) => [c.id, c.class]), [[2, 'bot'], [3, 'human']]);
  assert.equal(threads[1].resolved, null);
});

test('selectFeedback: a /pr-review report posted as a review body counts as the report', () => {
  const out = selectFeedback({ threads: [], reviews: [{ id: 'PRR_h', author: { login: 'alice' }, body: REPORT, state: 'COMMENTED', submittedAt: '2026-10-09T00:00:00Z' }] }, types);
  assert.equal(out.latestPrReview.id, 'PRR_h');
  assert.equal(out.source, null);
});

test('selectFeedback: no report → null; invalid input fails loudly', () => {
  assert.equal(selectFeedback({ threads: [] }, new Map()).latestPrReview, null);
  assert.throws(() => selectFeedback({}, new Map()), /threads/);
  assert.throws(() => selectFeedback({ threads: [] }, {}), /type index/);
});
